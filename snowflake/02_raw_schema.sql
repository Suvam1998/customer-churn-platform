-- 4. Ingestion Validation Query
SELECT
    COUNT(*) AS TOTAL_RAW_CUSTOMERS,
    COUNT(DISTINCT CUSTOMER_ID) AS DISTINCT_CUSTOMERS,
    SUM(CASE WHEN CHURN_LABEL = 'Yes' THEN 1 ELSE 0 END) AS HISTORICAL_CHURNED,
    ROUND(AVG(MONTHLY_CHARGES), 2) AS AVG_MONTHLY_CHARGES
FROM CUSTOMERS;
